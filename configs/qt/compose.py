import argparse
import fcntl
import hashlib
import json
from pathlib import Path
import re
import tempfile

from artwork import svg


SOURCE = Path(__file__).resolve().parent
TOKENS = (
    "primary", "on_primary", "surface", "surface_container_low", "surface_container",
    "surface_container_high", "on_surface", "on_surface_variant", "outline_variant",
    "tertiary", "error", "on_error",
)
HEADER = "# generated by skadi-qt-theme\n"


def read_palette(path):
    palette = json.loads(path.read_text())
    if not isinstance(palette, dict) or set(palette) != set(TOKENS):
        raise ValueError(f"Expected palette tokens: {', '.join(TOKENS)}")
    for token, value in palette.items():
        if not isinstance(value, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
            raise ValueError(f"Invalid palette color {token}: {value!r}")
    return {token: value.lower() for token, value in palette.items()}


def mix(first, second, weight):
    return "#" + "".join(
        f"{round(int(first[index:index + 2], 16) * weight + int(second[index:index + 2], 16) * (1 - weight)):02x}"
        for index in (1, 3, 5)
    )


def materials(palette):
    r = dict(palette)
    primary = r["primary"]
    r.update(
        shell=mix(primary, r["surface_container_low"], 0.08),
        panel=mix(primary, r["surface_container"], 0.06),
        field=mix(primary, r["surface_container_high"], 0.04),
        border=mix(primary, r["outline_variant"], 0.35),
        strong_border=mix(primary, r["outline_variant"], 0.65),
        disabled_text=mix(r["on_surface"], r["surface_container"], 0.50),
        selected_hover=mix(r["on_primary"], primary, 0.12),
        selected_pressed=mix(r["on_primary"], primary, 0.22),
    )
    r["hover"] = mix(primary, r["panel"], 0.12)
    r["pressed"] = mix(primary, r["panel"], 0.22)
    return r


def qtct_palette(r):
    # qpalette roles are positional in qtct, including NoRole at index 17.
    active = [
        r["on_surface"], r["panel"], r["strong_border"], r["border"], r["shell"],
        r["border"], r["on_surface"], r["on_surface"], r["on_surface"], r["field"],
        r["shell"], "#000000", r["primary"], r["on_primary"], r["primary"],
        r["tertiary"], r["panel"], r["shell"], r["panel"], r["on_surface"],
        r["on_surface_variant"], r["primary"],
    ]
    inactive = list(active)
    for index in (0, 6, 8):
        inactive[index] = r["on_surface_variant"]
    disabled = list(inactive)
    for index in (0, 6, 8, 13, 19, 20):
        disabled[index] = r["disabled_text"]
    disabled[12] = r["panel"]
    return HEADER + "[ColorScheme]\n" + "".join(
        f"{state}_colors={', '.join(colors)}\n"
        for state, colors in [("active", active), ("disabled", disabled), ("inactive", inactive)]
    )


def compose(palette):
    r = materials(palette)
    config = (SOURCE / "Skadi.kvconfig").read_text()
    config = re.sub(r"@([a-z_]+)@", lambda match: r[match[1]], config)
    return {"Skadi.svg": svg(r), "Skadi.kvconfig": HEADER + config,
            "qtct.conf": qtct_palette(r)}


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, prefix=".skadi-", delete=False) as temporary:
        temporary.write(content)
        temporary_path = Path(temporary.name)
    try:
        temporary_path.replace(path)
    finally:
        temporary_path.unlink(missing_ok=True)


def publish(config_home, files):
    runtime = config_home / "qt-theme"
    runtime.mkdir(parents=True, exist_ok=True)
    with (runtime / "publish.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        generations = runtime / "generations"
        digest = hashlib.sha256("".join(files.values()).encode()).hexdigest()
        generation = generations / digest
        link = config_home / "Kvantum/Skadi"
        if link.is_symlink():
            if link.resolve().parent != generations.resolve():
                raise ValueError(f"Refusing to replace unmanaged theme: {link}")
        elif link.exists():
            raise ValueError(f"Refusing to replace unmanaged theme: {link}")
        palettes = [config_home / version / "colors/reactive.conf" for version in ("qt5ct", "qt6ct")]
        for path in palettes:
            if path.is_symlink():
                raise ValueError(f"Refusing to replace palette symlink: {path}")
            if path.exists() and not path.read_text().startswith((HEADER, "# renderer-owned qtct palette for ")):
                raise ValueError(f"Refusing to replace unmanaged palette: {path}")
        generation.mkdir(parents=True, exist_ok=True)
        for name in ("Skadi.svg", "Skadi.kvconfig"):
            path = generation / name
            if path.exists():
                if path.read_text() != files[name]:
                    raise ValueError(f"Corrupt theme generation: {path}")
            else:
                atomic_write(path, files[name])
        link.parent.mkdir(parents=True, exist_ok=True)
        # publish only after both files are complete, keeping the last theme on failure.
        with tempfile.TemporaryDirectory(dir=link.parent, prefix=".Skadi-") as directory:
            temporary = Path(directory) / "theme"
            temporary.symlink_to(generation.resolve(), target_is_directory=True)
            temporary.replace(link)
        for path in palettes:
            atomic_write(path, files["qtct.conf"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--palette", type=Path)
    destination = parser.add_mutually_exclusive_group(required=True)
    destination.add_argument("--output", type=Path)
    destination.add_argument("--config-home", type=Path)
    args = parser.parse_args()
    path = args.palette or SOURCE / "fallback.json"
    if not path.exists() and args.config_home:
        path = SOURCE / "fallback.json"
    files = compose(read_palette(path))
    if args.output:
        args.output.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            atomic_write(args.output / name, content)
    else:
        publish(args.config_home, files)


if __name__ == "__main__":
    main()
