import argparse
import os
from pathlib import Path
import tempfile


GENERATED = "/* generated by skadi-gtk-apply */\n"
IMPORT = '@import url("skadi.css");'
LEGACY_IMPORTS = {
    '@import url("reactive.css");',
    '@import url("../gtk-theme/widgets.css");',
}


def write_changed(path, content):
    if path.exists() and path.read_text() == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, prefix=".skadi-", delete=False) as output:
        output.write(content)
        output.flush()
        os.fsync(output.fileno())
        temporary = output.name
    os.replace(temporary, path)


def prepare(theme, config_home):
    updates = []
    for version in ["gtk-3.0", "gtk-4.0"]:
        packaged = theme / "share" / "themes" / "Skadi" / version / "gtk.css"
        if not packaged.is_file():
            raise ValueError(f"missing packaged GTK stylesheet: {packaged}")
        directory = config_home / version
        wrapper = directory / "skadi.css"
        css = directory / "gtk.css"
        if wrapper.is_symlink():
            raise ValueError(f"refusing to replace a symlink: {wrapper}")
        if wrapper.exists() and not wrapper.read_text().startswith(GENERATED):
            raise ValueError(f"refusing to replace an unmanaged stylesheet: {wrapper}")
        original = css.read_text() if css.exists() else ""
        lines = [line for line in original.splitlines(keepends=True)
                 if line.strip() not in LEGACY_IMPORTS and line.strip() != IMPORT]
        remainder = "".join(lines)
        content = GENERATED
        # gtk3 resolves raw colors across providers; keep its components below native high contrast.
        if version == "gtk-4.0":
            content += f'@import url("{packaged.as_uri()}");\n'
        if (directory / "reactive.css").is_file():
            content += '@import url("reactive.css");\n'
        updated = IMPORT + "\n" + remainder
        if css.is_symlink() and updated != original:
            raise ValueError(f"refusing to replace a symlink: {css}")
        updates.extend([(wrapper, content), (css, updated)])
    return updates


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--theme", required=True, type=Path)
    parser.add_argument("--config-home", type=Path,
                        default=Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")))
    args = parser.parse_args(argv)
    try:
        updates = prepare(args.theme.resolve(), args.config_home.expanduser().absolute())
        for path, content in updates:
            write_changed(path, content)
    except (OSError, ValueError) as error:
        parser.exit(1, f"skadi-gtk-apply: {error}\n")


if __name__ == "__main__":
    main()
