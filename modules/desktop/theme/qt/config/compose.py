import argparse
import fcntl
import hashlib
import json
from pathlib import Path
import re
import tempfile

from artwork import svg


SOURCE = Path(__file__).resolve().parent
TOKENS = (
    "primary", "on_primary", "surface", "surface_container_low", "surface_container",
    "surface_container_high", "on_surface", "on_surface_variant", "outline_variant",
    "tertiary", "error", "on_error", "warning", "success",
)
HEADER = "; generated by skadi-qt-theme\n"
KDE_HEADER = "# generated by skadi-qt-theme\n"
MANAGED_HEADERS = (HEADER, KDE_HEADER, "# renderer-owned qtct palette for ")


def read_palette(path):
    palette = json.loads(path.read_text())
    if not isinstance(palette, dict) or not set(palette) <= set(TOKENS):
        raise ValueError(f"Expected palette tokens: {', '.join(TOKENS)}")
    # a palette rendered before the templates gained a role stays valid until the next theme
    # event renders it again; the missing roles come from the fallback palette meanwhile.
    if path != SOURCE / "fallback.json":
        palette = {**json.loads((SOURCE / "fallback.json").read_text()), **palette}
    for token, value in palette.items():
        if not isinstance(value, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
            raise ValueError(f"Invalid palette color {token}: {value!r}")
    return {token: value.lower() for token, value in palette.items()}


def mix(first, second, weight):
    return "#" + "".join(
        f"{round(int(first[index:index + 2], 16) * weight + int(second[index:index + 2], 16) * (1 - weight)):02x}"
        for index in (1, 3, 5)
    )


def materials(palette):
    r = dict(palette)
    primary = r["primary"]
    r.update(
        shell=mix(primary, r["surface_container_low"], 0.08),
        panel=mix(primary, r["surface_container"], 0.06),
        field=mix(primary, r["surface_container_high"], 0.04),
        border=mix(primary, r["outline_variant"], 0.35),
        strong_border=mix(primary, r["outline_variant"], 0.65),
        disabled_text=mix(r["on_surface"], r["surface_container"], 0.50),
        selected_hover=mix(r["on_primary"], primary, 0.12),
        selected_pressed=mix(r["on_primary"], primary, 0.22),
    )
    r["hover"] = mix(primary, r["panel"], 0.12)
    r["pressed"] = mix(primary, r["panel"], 0.22)
    return r


def alpha(color, value):
    return f"#{value:02x}{color[1:]}"


def qtct_palette(r):
    # qml-only processes never load kvantum and paint from this palette, so it mirrors
    # kvantum's standardPalette role for role, alpha included. qpalette roles are positional in
    # qtct, including NoRole at index 17.
    active = [
        r["on_surface"], r["panel"], r["strong_border"], r["border"], r["shell"],
        r["border"], r["on_surface"], r["error"], r["on_surface"], r["field"],
        r["shell"], "#000000", r["primary"], r["on_primary"], r["primary"],
        r["tertiary"], r["panel"], r["shell"], r["panel"], r["on_surface"],
        alpha(r["on_surface"], 128), r["primary"],
    ]
    # kvantum has no inactive button text key, so ButtonText stays active.
    inactive = list(active)
    for index in (0, 6):
        inactive[index] = r["on_surface_variant"]
    disabled = list(active)
    for index in (0, 6, 8):
        disabled[index] = r["disabled_text"]
    disabled[13] = alpha(r["on_primary"], 102)
    return HEADER + "[ColorScheme]\n" + "".join(
        f"{state}_colors={', '.join(colors)}\n"
        for state, colors in [("active", active), ("disabled", disabled), ("inactive", inactive)]
    )


def kde_groups(r):
    def rgb(color, value=None):
        channels = [str(int(color[index:index + 2], 16)) for index in (1, 3, 5)]
        return ",".join(channels + ([str(value)] if value is not None else []))

    def colors(background, alternate, text, **overrides):
        group = dict(
            BackgroundNormal=rgb(background), BackgroundAlternate=rgb(alternate),
            ForegroundNormal=rgb(text), ForegroundInactive=rgb(r["on_surface"], 128),
            ForegroundActive=rgb(r["primary"]), ForegroundLink=rgb(r["primary"]),
            ForegroundVisited=rgb(r["tertiary"]), ForegroundNegative=rgb(r["error"]),
            ForegroundNeutral=rgb(r["warning"]), ForegroundPositive=rgb(r["success"]),
            DecorationFocus=rgb(r["primary"]), DecorationHover=rgb(r["strong_border"]),
        )
        group.update(overrides)
        return group

    # createApplicationPalette reads PlaceholderText from View's inactive foreground, so it
    # carries kvantum's half-alpha text. an [Inactive] subgroup replaces its set wholesale
    # instead of overlaying it, hence the full copies.
    shell = colors(r["shell"], r["panel"], r["on_surface"])
    view = colors(r["field"], r["panel"], r["on_surface"])
    muted = dict(ForegroundNormal=rgb(r["on_surface_variant"]))
    on_primary = rgb(r["on_primary"])
    return {
        "Colors:Button": colors(r["panel"], r["hover"], r["on_surface"]),
        "Colors:Complementary": colors(r["surface"], r["shell"], r["on_surface"]),
        "Colors:Header": shell,
        "Colors:Header][Inactive": dict(shell, **muted),
        # on_error is the dark-on-pale (or pale-on-dark) error ink that stays legible on the
        # primary fill, where plain error would vanish.
        "Colors:Selection": colors(
            r["primary"], r["selected_hover"], r["on_primary"],
            ForegroundInactive=rgb(mix(r["on_primary"], r["primary"], 0.6)),
            ForegroundActive=on_primary, ForegroundLink=on_primary, ForegroundVisited=on_primary,
            ForegroundNegative=rgb(r["on_error"]), DecorationHover=on_primary,
        ),
        "Colors:Tooltip": colors(r["panel"], r["shell"], r["on_surface"]),
        "Colors:View": view,
        "Colors:View][Inactive": dict(view, **muted),
        "Colors:Window": shell,
        "Colors:Window][Inactive": dict(shell, **muted),
        # kvantum keeps backgrounds and selection in inactive windows and only fades disabled
        # text halfway into its background.
        "ColorEffects:Disabled": dict(
            Enable="true", IntensityEffect="0", IntensityAmount="0", ColorEffect="0",
            ColorAmount="0", ContrastEffect="1", ContrastAmount="0.5",
        ),
        "ColorEffects:Inactive": dict(Enable="false", ChangeSelectionColor="false"),
    }


def ini(groups):
    return "".join(
        f"\n[{name}]\n" + "".join(f"{key}={value}\n" for key, value in entries.items())
        for name, entries in groups.items()
    )


def compose(palette):
    r = materials(palette)
    config = (SOURCE / "Skadi.kvconfig").read_text()
    config = re.sub(r"@([a-z_]+)@", lambda match: r[match[1]], config)
    groups = kde_groups(r)
    scheme = KDE_HEADER + "[General]\nColorScheme=Skadi\nName=Skadi\n" + ini(groups)
    return {"Skadi.svg": svg(r), "Skadi.kvconfig": HEADER + config,
            "qtct.conf": qtct_palette(r), "Skadi.colors": scheme,
            "kdeglobals.groups": ini(groups)}


def merge_kdeglobals(existing, groups):
    # kdeglobals belongs to every kf6 app, so only the colour groups and the scheme id are
    # replaced; other groups and keys keep their text and order.
    blocks, current = [], ["", []]
    for line in existing.splitlines():
        if line.startswith("["):
            blocks.append(current)
            current = [line, []]
        elif line.strip():
            current[1].append(line)
    blocks.append(current)
    scheme = "ColorScheme=Skadi"
    text, named = "", False
    for header, lines in blocks:
        if header.startswith(("[Colors:", "[ColorEffects:")):
            continue
        if header == "[UiSettings]":
            lines = [line for line in lines
                     if not re.match(r"ColorScheme\s*(\[[^]]*\])?\s*=", line)]
            if not named:
                lines.insert(0, scheme)
                named = True
        if header or lines:
            text += (f"\n{header}\n" if header else "") + "".join(f"{line}\n" for line in lines)
    if not named:
        text += f"\n[UiSettings]\n{scheme}\n"
    return text.lstrip("\n") + groups


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, prefix=".skadi-", delete=False) as temporary:
        temporary.write(content)
        temporary_path = Path(temporary.name)
    try:
        temporary_path.replace(path)
    finally:
        temporary_path.unlink(missing_ok=True)


def publish(config_home, data_home, files):
    runtime = config_home / "qt-theme"
    runtime.mkdir(parents=True, exist_ok=True)
    with (runtime / "publish.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        generations = runtime / "generations"
        digest = hashlib.sha256("".join(files.values()).encode()).hexdigest()
        generation = generations / digest
        link = config_home / "Kvantum/Skadi"
        if link.is_symlink():
            if link.resolve().parent != generations.resolve():
                raise ValueError(f"Refusing to replace unmanaged theme: {link}")
        elif link.exists():
            raise ValueError(f"Refusing to replace unmanaged theme: {link}")
        palettes = [config_home / version / "colors/reactive.conf" for version in ("qt5ct", "qt6ct")]
        for path in palettes:
            if path.is_symlink():
                raise ValueError(f"Refusing to replace palette symlink: {path}")
            if path.exists() and not path.read_text().startswith(MANAGED_HEADERS):
                raise ValueError(f"Refusing to replace unmanaged palette: {path}")
        scheme = data_home / "color-schemes/Skadi.colors"
        if scheme.is_symlink() or (scheme.exists() and not scheme.read_text().startswith(MANAGED_HEADERS)):
            raise ValueError(f"Refusing to replace unmanaged color scheme: {scheme}")
        kdeglobals = config_home / "kdeglobals"
        if kdeglobals.is_symlink():
            raise ValueError(f"Refusing to replace kdeglobals symlink: {kdeglobals}")
        generation.mkdir(parents=True, exist_ok=True)
        for name in ("Skadi.svg", "Skadi.kvconfig"):
            path = generation / name
            if path.exists():
                if path.read_text() != files[name]:
                    raise ValueError(f"Corrupt theme generation: {path}")
            else:
                atomic_write(path, files[name])
        link.parent.mkdir(parents=True, exist_ok=True)
        # publish only after both files are complete, keeping the last theme on failure.
        with tempfile.TemporaryDirectory(dir=link.parent, prefix=".Skadi-") as directory:
            temporary = Path(directory) / "theme"
            temporary.symlink_to(generation.resolve(), target_is_directory=True)
            temporary.replace(link)
        for path in palettes:
            atomic_write(path, files["qtct.conf"])
        # the scheme lands before kdeglobals names it, so a kf6 app never resolves a missing id.
        atomic_write(scheme, files["Skadi.colors"])
        existing = kdeglobals.read_text() if kdeglobals.exists() else ""
        atomic_write(kdeglobals, merge_kdeglobals(existing, files["kdeglobals.groups"]))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--palette", type=Path)
    destination = parser.add_mutually_exclusive_group(required=True)
    destination.add_argument("--output", type=Path)
    destination.add_argument("--config-home", type=Path)
    parser.add_argument("--data-home", type=Path)
    args = parser.parse_args()
    if args.config_home and not args.data_home:
        parser.error("--config-home needs --data-home for the kde color scheme")
    path = args.palette or SOURCE / "fallback.json"
    if not path.exists() and args.config_home:
        path = SOURCE / "fallback.json"
    files = compose(read_palette(path))
    if args.output:
        args.output.mkdir(parents=True, exist_ok=True)
        for name in ("Skadi.svg", "Skadi.kvconfig", "qtct.conf"):
            atomic_write(args.output / name, files[name])
    else:
        publish(args.config_home, args.data_home, files)


if __name__ == "__main__":
    main()
